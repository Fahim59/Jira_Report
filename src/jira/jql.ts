import { InvalidJqlError, type CompiledFilter } from '../services/custom/filter.js';
import { JiraError, type JiraClient, type RequestOptions } from './client.js';

interface JqlParseResponse {
  queries?: Array<{ query?: string; errors?: string[] }>;
}

/** Jira's message from a JiraError ("Jira 400 on /path: <detail>" → "<detail>"). */
function jiraDetail(err: JiraError): string {
  return err.message.replace(/^Jira \d+ on \S+?: /, '');
}

/**
 * Validates the user's JQL and the final compiled JQL with POST /rest/api/3/jql/parse (strict: unknown fields
 * and values are errors). Throws InvalidJqlError (400) carrying Jira's message. Skipped when there is neither
 * user JQL nor a JQL condition, since the base clauses are generated by the app.
 */
export async function validateCustomJql(
  client: JiraClient,
  compiled: Pick<CompiledFilter, 'where' | 'conditionFieldIds'>,
  userJql: string | undefined,
  opts: RequestOptions = {},
): Promise<void> {
  if (!userJql && compiled.conditionFieldIds.length === 0) return;
  if (!client.post) throw new Error('This Jira client cannot validate JQL (no POST support)');

  const queries = userJql ? [userJql, compiled.where] : [compiled.where];
  let res: JqlParseResponse;
  try {
    res = await client.post<JqlParseResponse>('/rest/api/3/jql/parse', { queries }, { validation: 'strict' }, opts);
  } catch (err) {
    if (err instanceof JiraError && err.status === 400) throw new InvalidJqlError(`Invalid JQL: ${jiraDetail(err)}`);
    throw err;
  }

  const errorsOf = (i: number) => res.queries?.[i]?.errors?.filter(Boolean) ?? [];
  if (userJql && errorsOf(0).length) throw new InvalidJqlError(`Invalid JQL: ${errorsOf(0).join('; ')}`);
  const finalErrors = errorsOf(queries.length - 1);
  if (finalErrors.length) throw new InvalidJqlError(`The filters are not valid in Jira: ${finalErrors.join('; ')}`);
}

/**
 * Which of `clauses` Jira's parser accepts (strict), in one POST /rest/api/3/jql/parse. A clause Jira rejects (an
 * operator the field does not support, an unknown value, ...) is simply not returned; if Jira rejects the whole call
 * with 400, none is. Other errors propagate. No call for an empty list.
 */
export async function acceptedJqlClauses(
  client: JiraClient,
  clauses: readonly string[],
  opts: RequestOptions = {},
): Promise<Set<string>> {
  const queries = [...new Set(clauses)];
  if (!queries.length) return new Set();
  if (!client.post) throw new Error('This Jira client cannot validate JQL (no POST support)');
  let res: JqlParseResponse;
  try {
    res = await client.post<JqlParseResponse>('/rest/api/3/jql/parse', { queries }, { validation: 'strict' }, opts);
  } catch (err) {
    if (err instanceof JiraError && err.status === 400) return new Set();
    throw err;
  }
  return new Set(queries.filter((_, i) => res.queries?.[i] && !(res.queries[i]!.errors ?? []).some(Boolean)));
}

/**
 * Validates every sheet's JQL in one POST /rest/api/3/jql/parse (strict), both alone and as
 * `(global JQL) AND (sheet JQL)`. Throws InvalidJqlError (400) naming the sheet. No call without sheet JQL.
 */
export async function validateSheetJql(
  client: JiraClient,
  globalWhere: string,
  sheets: ReadonlyArray<{ name: string; jql?: string }>,
  opts: RequestOptions = {},
): Promise<void> {
  const withJql = sheets.filter((s): s is { name: string; jql: string } => !!s.jql);
  if (!withJql.length) return;
  if (!client.post) throw new Error('This Jira client cannot validate JQL (no POST support)');

  const queries = withJql.flatMap((s) => [s.jql, `${globalWhere} AND (${s.jql})`]);
  let res: JqlParseResponse;
  try {
    res = await client.post<JqlParseResponse>('/rest/api/3/jql/parse', { queries }, { validation: 'strict' }, opts);
  } catch (err) {
    if (err instanceof JiraError && err.status === 400) throw new InvalidJqlError(`Invalid sheet JQL: ${jiraDetail(err)}`);
    throw err;
  }
  const errorsOf = (i: number) => res.queries?.[i]?.errors?.filter(Boolean) ?? [];
  withJql.forEach((s, i) => {
    const own = errorsOf(2 * i);
    if (own.length) throw new InvalidJqlError(`Sheet "${s.name}": invalid JQL: ${own.join('; ')}`);
    const combined = errorsOf(2 * i + 1);
    if (combined.length) throw new InvalidJqlError(`Sheet "${s.name}": the JQL is not valid in Jira: ${combined.join('; ')}`);
  });
}
